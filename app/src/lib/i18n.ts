const STORAGE_KEY = 'dadix-locale';

export function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === 'de' || stored === 'en') return stored;
  return 'en';
}

export function setStoredLocale(locale: Locale): void {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem(STORAGE_KEY, locale);
}

export function t(locale: Locale, key: string): string {
  const map = translations[locale];
  return map[key] ?? translations.en[key] ?? key;
}

const SYSTEM_NAME_KEYS: Record<string, string> = {
  'Alle Einträge': 'table.allEntries',
  'All entries': 'table.allEntries',
  'Neue Ansicht': 'table.newView',
  'New view': 'table.newView',
  Ansicht: 'table.newView',
  'Neue Tabelle': 'table.newTable',
  'New table': 'table.newTable',
};

/** Translate leftover German/English system defaults when the UI language differs. */
export function localizeSystemName(locale: Locale, name: string): string {
  const key = SYSTEM_NAME_KEYS[name];
  return key ? t(locale, key) : name;
}
