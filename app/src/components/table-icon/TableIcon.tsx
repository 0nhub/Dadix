const availableTableIcons = (() => Object.keys(Icons))();

function TableIcon({
  name,
  ...props
}: { name: string } & SVGAttributes<SVGElement> & LucideProps) {
  const Icon: ForwardRefExoticComponent<
    Omit<LucideProps, 'ref'> & RefAttributes<SVGSVGElement>
  > | null = (() => {
    if (`${name}` === 'defaultIcon') name = availableTableIcons[0];
    if (availableTableIcons.indexOf(name) < 0) return null;
    return Icons[name];
  })();
  if (!Icon) {
    return null;
  }
  return <Icon {...props} />;
}

export { TableIcon, availableTableIcons };
